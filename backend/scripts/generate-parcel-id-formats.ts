/**
 * Measures how each Ohio county punctuates its published parcel IDs and
 * writes src/parcels/parcelIdFormats.ts.
 *
 *   pnpm --filter @groundtruth/backend generate:id-formats
 *
 * A format records where separators sit: Franklin's `010-042534` is `3-6`.
 * Search uses these to turn a typed `010042534` back into the published
 * `010-042534`. Samples 4 × 1,000 IDs spread across each county; a format is
 * kept when it covers at least 1% of a county's sample.
 */
import { writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { OGRIP_PARCELS_LAYER } from "../src/parcels/ogrip.js";
import { OHIO_COUNTIES } from "../src/parcels/ohioCounties.js";
import { isKeyableParcelId } from "../src/parcels/parcelKey.js";
import { idFormat } from "../src/parcels/parcelIdSearch.js";

const PAGE = 1_000;
const PAGES = 4;
const MIN_SHARE = 0.01;

async function getJson(params: Record<string, string>): Promise<unknown> {
  const url = `${OGRIP_PARCELS_LAYER}/query?${new URLSearchParams(params)}`;
  for (let attempt = 1; ; attempt += 1) {
    try {
      const res = await fetch(url, { signal: AbortSignal.timeout(90_000) });
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      return await res.json();
    } catch (error) {
      if (attempt === 3) throw error;
    }
  }
}

async function measure(county: string): Promise<Map<string, number>> {
  const where = `County='${county.replaceAll("'", "''")}' AND LocalParcelID IS NOT NULL`;
  const countBody = (await getJson({
    where,
    returnCountOnly: "true",
    f: "json",
  })) as {
    count: number;
  };
  const formats = new Map<string, number>();
  let sampled = 0;
  for (let page = 0; page < PAGES; page += 1) {
    const offset = Math.floor((countBody.count * page) / PAGES);
    const body = (await getJson({
      where,
      outFields: "LocalParcelID",
      orderByFields: "OBJECTID",
      resultOffset: String(offset),
      resultRecordCount: String(PAGE),
      returnGeometry: "false",
      f: "json",
    })) as { features: { attributes: { LocalParcelID: string } }[] };
    for (const { attributes } of body.features) {
      const id = attributes.LocalParcelID;
      if (!isKeyableParcelId(id)) continue;
      sampled += 1;
      const format = idFormat(id);
      formats.set(format, (formats.get(format) ?? 0) + 1);
    }
  }
  const kept = new Map<string, number>();
  for (const [format, n] of formats) {
    if (/[-.]/.test(format) && n / sampled >= MIN_SHARE) kept.set(format, n);
  }
  return kept;
}

const byFormat = new Map<string, Set<string>>();
const queue = [...OHIO_COUNTIES];
await Promise.all(
  Array.from({ length: 6 }, async () => {
    for (let county = queue.shift(); county; county = queue.shift()) {
      const formats = await measure(county.name);
      for (const format of formats.keys()) {
        if (!byFormat.has(format)) byFormat.set(format, new Set());
        byFormat.get(format)?.add(county.fips);
      }
      console.log(
        `${county.name}: ${[...formats.keys()].join(" ") || "(no separators)"}`,
      );
    }
  }),
);

const lines = [...byFormat.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(
    ([format, fips]) =>
      `  ["${format}", [${[...fips]
        .sort()
        .map((f) => `"${f}"`)
        .join(", ")}]],`,
  );
const out = `// Generated by scripts/generate-parcel-id-formats.ts on ${new Date().toISOString().slice(0, 10)}. Do not edit.
// Separator layouts of published OGRIP LocalParcelIDs, with the counties using each.
// A digit is the length of an alphanumeric run: Franklin's 010-042534 is "3-6".
export const PARCEL_ID_FORMATS: readonly (readonly [string, readonly string[]])[] = [
${lines.join("\n")}
];
`;
const target = join(
  dirname(fileURLToPath(import.meta.url)),
  "../src/parcels/parcelIdFormats.ts",
);
await writeFile(target, out);
console.log(`wrote ${byFormat.size} formats to ${target}`);
