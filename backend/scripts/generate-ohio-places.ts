/**
 * Writes src/parcels/ohioPlaces.ts: Ohio city, village, CDP, and township
 * names mapped to the counties they lie in, from the Census Bureau's 2020
 * reference files.
 *
 *   pnpm --filter @groundtruth/backend generate:places
 *
 * Address search uses it to scope its fallback to the counties a typed city
 * names (Johnstown → Licking; Columbus → Delaware, Fairfield, Franklin).
 */
import { writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { normalizePlaceName } from "../src/parcels/addressQuery.js";

const SOURCES = [
  "https://www2.census.gov/geo/docs/reference/codes2020/national_place_by_county2020.txt",
  "https://www2.census.gov/geo/docs/reference/codes2020/national_cousub2020.txt",
];
const TYPE_SUFFIX = / (city|village|town|township|CDP)$/i;

const counties = new Map<string, Set<string>>();
for (const url of SOURCES) {
  const res = await fetch(url, { signal: AbortSignal.timeout(120_000) });
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  const [header = "", ...rows] = (await res.text()).split(/\r?\n/);
  const columns = header.split("|");
  const at = (name: string) => columns.indexOf(name);
  const nameColumn = at("PLACENAME") >= 0 ? at("PLACENAME") : at("COUSUBNAME");
  for (const row of rows) {
    const cells = row.split("|");
    if (cells[at("STATE")] !== "OH") continue;
    const raw = cells[nameColumn] ?? "";
    const name = normalizePlaceName(raw.replace(TYPE_SUFFIX, ""));
    const fips = `39${cells[at("COUNTYFP")]}`;
    if (!name || /^39\d{3}$/.test(fips) === false) continue;
    if (!counties.has(name)) counties.set(name, new Set());
    counties.get(name)?.add(fips);
  }
}

const lines = [...counties.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(
    ([name, fips]) =>
      `  ${JSON.stringify(name)}: [${[...fips]
        .sort()
        .map((f) => `"${f}"`)
        .join(", ")}],`,
  );
const out = `// Generated by scripts/generate-ohio-places.ts on ${new Date().toISOString().slice(0, 10)}. Do not edit.
// Ohio place and township names (Census 2020 reference files) → county FIPS codes.
// Sources: ${SOURCES.join(" , ")}
export const OHIO_PLACE_COUNTIES: Readonly<Record<string, readonly string[]>> = {
${lines.join("\n")}
};
`;
const target = join(
  dirname(fileURLToPath(import.meta.url)),
  "../src/parcels/ohioPlaces.ts",
);
await writeFile(target, out);
console.log(`wrote ${counties.size} Ohio place names to ${target}`);
